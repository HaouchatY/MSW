def slice_weights(channels: int, level_sizes: list[int], scheme: str = "P1s") -> list[float]:
    """Fixed convex weights over the estimator's slices.

    ``P1s`` (default) is ``4**-l / sigmabar_s`` -- the frequency-flat factor of
    the published distance, divided by the canonical response scale so that a
    quiet slice is not drowned by a loud one.  ``flat`` reproduces the v0.2
    weighting (``4**-l``, uniform within a level) exactly.

    Falls back to ``flat`` when the canonical table does not cover the
    configuration, so an unusual bank or depth still returns a valid metric.
    """
    lev = []
    for l, s in enumerate(level_sizes):
        lev += [l] * s
    if scheme == "flat":
        w = [4.0 ** (-l) for l in lev]
    else:
        sb = []
        for l, s in enumerate(level_sizes):
            key = f"C{channels}|L{l}"
            v = SIGMA_SHAPE.get(key)
            if v is None or len(v) != s:
                return slice_weights(channels, level_sizes, "flat")
            sb += list(v)
        gamma = 2.0 if scheme == "P2s" else 1.0
        w = [4.0 ** (-l) / (s ** gamma) for l, s in zip(lev, sb)]
    t = sum(w)
    return [x / t for x in w]
